import { chromium } from "playwright-core";
import { readFileSync } from "node:fs";
import pg from "pg";
const BASE = "http://localhost:3000";
const db = new pg.Client("postgresql://postgres@127.0.0.1:5432/meetready_e2e"); await db.connect();
await db.query(`update "user" set username = null, time_zone = 'UTC' where id = 'u_sakif'`);
const browser = await chromium.launch({ executablePath: "/usr/bin/google-chrome", args: ["--no-sandbox"] });
const ctx = await browser.newContext({ timezoneId: "Asia/Dhaka" });
await ctx.addCookies([{ name: "better-auth.session_token", value: readFileSync("/tmp/session-cookie.txt", "utf8"), url: BASE }]);
const p = await ctx.newPage(); const errors = []; p.on("pageerror", (e) => errors.push(String(e)));
await p.goto(`${BASE}/onboarding`);
const box = p.getByRole("combobox", { name: "Timezone" }); await box.waitFor(); await p.waitForTimeout(800);
console.log("• detected shown:", await box.inputValue());
await box.click(); await box.fill("tokyo"); await box.press("Enter");
console.log("• picked:", await box.inputValue());
await p.getByLabel("Username").fill("sakif");
await p.getByRole("button", { name: "Continue" }).click(); await p.waitForURL(/dashboard/);
const { rows } = await db.query(`select username, time_zone from "user" where id = 'u_sakif'`);
console.log("• saved:", rows[0], "errors:", errors.length ? errors : "none");
await db.query(`update "user" set time_zone = 'Asia/Dhaka' where id = 'u_sakif'`);
await db.end(); await browser.close();
