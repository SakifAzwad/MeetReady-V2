import { chromium } from "playwright-core";
import { readFileSync } from "node:fs";
const BASE = "http://localhost:3000";
const browser = await chromium.launch({ executablePath: "/usr/bin/google-chrome", args: ["--no-sandbox"] });
const ctx = await browser.newContext({ viewport: { width: 1280, height: 800 }, timezoneId: "Europe/London", recordVideo: { dir: "/tmp/vid8", size: { width: 1280, height: 800 } } });
await ctx.grantPermissions(["clipboard-read", "clipboard-write"], { origin: BASE });
const p = await ctx.newPage(); const w = (ms) => p.waitForTimeout(ms);
await p.goto(BASE); await p.getByText(/ now$/).first().waitFor(); await w(1200);
const hero = p.getByRole("combobox", { name: "Or search any city" });
await hero.click(); await w(300); await hero.pressSequentially("new y", { delay: 120 }); await w(700); await hero.press("Enter"); await w(1600);
await p.goto(`${BASE}/sakif/intro`); const g = p.getByRole("group", { name: /^Times on/ }); await g.waitFor(); await p.mouse.wheel(0, 120); await w(1500);
await g.locator("button[aria-pressed]:visible").nth(1).click(); await w(700);
await p.getByRole("button", { name: "Continue" }).click(); await p.getByLabel("Name").waitFor(); await w(1500);
await p.getByRole("table").locator("button:not([disabled])").nth(2).click(); await w(1500);
const tz = p.getByRole("combobox", { name: "Times shown in" }); await tz.scrollIntoViewIfNeeded(); await tz.click(); await w(300);
await tz.pressSequentially("india", { delay: 120 }); await w(900); await tz.press("Enter"); await w(1500);
await ctx.addCookies([{ name: "better-auth.session_token", value: readFileSync("/tmp/session-cookie.txt", "utf8"), url: BASE }]);
await p.goto(`${BASE}/dashboard`); await p.getByText("Your booking page").waitFor(); await p.mouse.wheel(0, 180); await w(1300);
await p.getByRole("link", { name: "Next 7 days" }).click(); await w(1300);
await p.getByRole("link", { name: "Next 7 days" }).click(); await w(1300);
await p.getByRole("link", { name: "Back to today" }).click(); await w(1300);
await p.locator("#share-heading").scrollIntoViewIfNeeded(); await w(500);
const their = p.getByRole("combobox", { name: "Their timezone" }); await their.click(); await their.pressSequentially("london", { delay: 110 }); await their.press("Enter"); await w(500);
await p.getByRole("button", { name: "Suggest 3 times" }).click(); await p.getByLabel("Message to paste").waitFor(); await w(1200);
await p.getByRole("button", { name: "Copy message" }).click(); await w(1500);
await ctx.close(); await browser.close();
