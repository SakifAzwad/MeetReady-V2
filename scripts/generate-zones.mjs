// Builds src/lib/scheduling/zone-data.generated.ts from the IANA tz database's
// zone.tab (country + coordinates of each zone's principal city) and the
// backward links (old names such as Asia/Calcutta). Run: node scripts/generate-zones.mjs [tzdata dir]
// Re-run when the tz database updates; the output is committed so the app
// doesn't depend on the build machine having tzdata installed.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const dir = process.argv[2] ?? "/usr/share/zoneinfo";
const zi = readFileSync(path.join(dir, "tzdata.zi"), "utf8");
const version = zi.match(/^# version (\S+)/m)?.[1] ?? "unknown";

// ISO 6709: ±DDMM or ±DDMMSS for latitude, ±DDDMM or ±DDDMMSS for longitude.
function coord(text, degDigits) {
  const sign = text[0] === "-" ? -1 : 1;
  const d = Number(text.slice(1, 1 + degDigits));
  const m = Number(text.slice(1 + degDigits, 3 + degDigits));
  const s = Number(text.slice(3 + degDigits) || 0);
  return Math.round(sign * (d + m / 60 + s / 3600) * 100) / 100;
}

const zones = {};
for (const line of readFileSync(path.join(dir, "zone.tab"), "utf8").split("\n")) {
  if (!line || line.startsWith("#")) continue;
  const [country, iso6709, zone] = line.split("\t");
  const [, lat, lon] = iso6709.match(/^([+-]\d+)([+-]\d+)$/);
  zones[zone] = [country, coord(lat, 2), coord(lon, 3)];
}

const aliases = {};
for (const line of zi.split("\n")) {
  const m = line.match(/^L (\S+) (\S+)$/);
  if (m && zones[m[1]]) aliases[m[2]] = m[1];
}

const out = `// Generated by scripts/generate-zones.mjs from tzdata ${version}. Do not edit by hand.
// [country code, latitude, longitude] of each zone's principal city (zone.tab).

export const TZDATA_VERSION = ${JSON.stringify(version)};

export const ZONES: Record<string, readonly [country: string, lat: number, lon: number]> = ${JSON.stringify(zones)};

/** Old or alternative names (e.g. "Asia/Calcutta") -> the zone.tab name ("Asia/Kolkata"). */
export const ZONE_ALIASES: Record<string, string> = ${JSON.stringify(aliases)};
`;
writeFileSync("src/lib/scheduling/zone-data.generated.ts", out);
// eslint-disable-next-line no-console -- a CLI script reporting what it wrote
console.log(`tzdata ${version}: ${Object.keys(zones).length} zones, ${Object.keys(aliases).length} aliases`);
